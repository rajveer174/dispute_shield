// Shared helpers for experiments/. Every script prints or writes totals only, never raw rows or IDs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/** Written by: java -jar backend/target/dispute-shield.jar train --data=data
 *   --out=outputs/experiments/model_bundle.json.gz --experiments=outputs/experiments  (git-ignored) */
export const EXP_OUT = path.join(ROOT, 'outputs', 'experiments');

export function need(file) {
  if (!fs.existsSync(file)) {
    console.error(`Missing ${path.relative(ROOT, file)}. Run the experiments training first (see experiments/README.md).`);
    process.exit(1);
  }
  return file;
}

export function readCsv(file) {
  const [head, ...lines] = fs.readFileSync(need(file), 'utf8').trim().split(/\r?\n/);
  const cols = head.split(',');
  return lines.map((l) => {
    const v = l.split(',');
    return Object.fromEntries(cols.map((c, i) => [c, /^-?[\d.]+(e-?\d+)?$/i.test(v[i]) ? Number(v[i]) : v[i]]));
  });
}

export const report = () => JSON.parse(fs.readFileSync(need(path.join(EXP_OUT, 'training_report.json')), 'utf8'));

export function auc(p, y) {
  const idx = p.map((_, i) => i).sort((a, b) => p[a] - p[b]);
  let rank = 0, sumPos = 0, nPos = 0;
  for (let i = 0; i < idx.length;) {
    let j = i;
    while (j < idx.length && p[idx[j]] === p[idx[i]]) j++;
    const r = (i + j + 1) / 2;
    for (let k = i; k < j; k++) if (y[idx[k]] === 1) { sumPos += r; nPos++; }
    rank = j; i = j;
  }
  const nNeg = y.length - nPos;
  return nPos && nNeg ? (sumPos - nPos * (nPos + 1) / 2) / (nPos * nNeg) : NaN;
}

export const brier = (p, y) => p.reduce((s, v, i) => s + (v - y[i]) ** 2, 0) / p.length;
export const logLoss = (p, y) => -p.reduce((s, v, i) => {
  const q = Math.min(1 - 1e-12, Math.max(1e-12, v));
  return s + (y[i] ? Math.log(q) : Math.log(1 - q));
}, 0) / p.length;

/** Expected calibration error over 10 equal-count bins. */
export function ece(p, y, bins = 10) {
  const idx = p.map((_, i) => i).sort((a, b) => p[a] - p[b]);
  let e = 0;
  for (let b = 0; b < bins; b++) {
    const part = idx.slice(Math.floor((b * idx.length) / bins), Math.floor(((b + 1) * idx.length) / bins));
    if (!part.length) continue;
    const mp = part.reduce((s, i) => s + p[i], 0) / part.length, my = part.reduce((s, i) => s + y[i], 0) / part.length;
    e += (part.length / idx.length) * Math.abs(mp - my);
  }
  return e;
}

export const f3 = (x) => (Number.isFinite(x) ? x.toFixed(3) : '–');
export const pct = (x, d = 1) => (Number.isFinite(x) ? `${(100 * x).toFixed(d)}%` : '–');
export const usd = (x) => `${x < 0 ? '−' : ''}$${Math.round(Math.abs(x)).toLocaleString('en-US')}`;

export function table(cols, rows) {
  return [`| ${cols.join(' | ')} |`, `| ${cols.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

/** Writes RESULTS.md next to the calling script and echoes it. */
export function writeResults(metaUrl, title, body) {
  const out = path.join(path.dirname(fileURLToPath(metaUrl)), 'RESULTS.md');
  const text = `# ${title}\n\n_Generated by \`run.mjs\` on ${new Date().toISOString().slice(0, 10)}. Totals only._\n\n${body.trim()}\n`;
  fs.writeFileSync(out, text);
  console.log(text);
}
